-- ---------- 4. ai_usage (kunlik AI limiti — xarajatdan himoya) ----------
create table if not exists public.ai_usage (
  user_id uuid not null references auth.users(id) on delete cascade,
  day     date not null default current_date,
  count   integer not null default 0 check (count >= 0),
  primary key (user_id, day)
);

alter table public.ai_usage enable row level security;

-- Foydalanuvchi faqat o'z hisobini ko'ra oladi; yozish faqat consume_ai_quota() orqali.
drop policy if exists "ai_usage_select_own" on public.ai_usage;
create policy "ai_usage_select_own" on public.ai_usage
  for select to authenticated using ((select auth.uid()) = user_id);

-- Bitta foydalanuvchi kuniga nechta AI savol bera oladi: shu yerdagi v_limit ni o'zgartiring.
create or replace function public.consume_ai_quota()
returns table (allowed boolean, used integer, quota integer)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_limit constant integer := 50;
  v_uid   uuid := auth.uid();
  v_count integer;
begin
  if v_uid is null then
    raise exception 'Not authenticated' using errcode = '28000';
  end if;

  insert into public.ai_usage as u (user_id, day, count)
  values (v_uid, current_date, 1)
  on conflict (user_id, day)
  do update set count = u.count + 1
  where u.count < v_limit
  returning u.count into v_count;

  if v_count is null then
    select u.count into v_count from public.ai_usage u
    where u.user_id = v_uid and u.day = current_date;
    return query select false, v_count, v_limit;
  end if;

  return query select true, v_count, v_limit;
end;
$$;

-- ---------- 5. Statistika funksiyalari (RLS ostida, security invoker) ----------
create or replace function public.get_my_stats()
returns jsonb
language sql
stable
security invoker
set search_path = ''
as $$
  select jsonb_build_object(
    'tests',   count(*),
    'correct', coalesce(sum(p.score), 0),
    'by_subject', coalesce((
      select jsonb_object_agg(s.subject, jsonb_build_object('tests', s.t, 'correct', s.c))
      from (
        select subject, count(*) as t, coalesce(sum(score), 0) as c
        from public.learning_progress
        where user_id = (select auth.uid()) and activity_type = 'quiz'
        group by subject
      ) s
    ), '{}'::jsonb)
  )
  from public.learning_progress p
  where p.user_id = (select auth.uid()) and p.activity_type = 'quiz';
$$;

-- Kunlik faollik (test javoblari + AI savollari): seriya va haftalik grafik uchun
create or replace function public.get_my_activity(p_days integer default 120, p_tz text default 'Asia/Tashkent')
returns table (day date, count integer)
language sql
stable
security invoker
set search_path = ''
as $$
  select x.d, count(*)::integer
  from (
    select (created_at at time zone p_tz)::date as d
    from public.learning_progress
    where user_id = (select auth.uid())
      and created_at > now() - make_interval(days => least(greatest(p_days, 1), 365))
    union all
    select (created_at at time zone p_tz)::date
    from public.chat_messages
    where user_id = (select auth.uid()) and role = 'user'
      and created_at > now() - make_interval(days => least(greatest(p_days, 1), 365))
  ) x
  group by x.d
  order by x.d;
$$;

