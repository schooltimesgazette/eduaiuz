-- EduAI optional progress storage schema.
-- Run this in Supabase SQL Editor. Row Level Security ensures users can only see their own rows.
create table if not exists public.learning_progress (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  subject text not null,
  activity_type text not null check (activity_type in ('quiz', 'lesson', 'goal')),
  score integer,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

alter table public.learning_progress enable row level security;

create policy "Users can read their own learning progress"
on public.learning_progress for select
to authenticated
using (auth.uid() = user_id);

create policy "Users can add their own learning progress"
on public.learning_progress for insert
to authenticated
with check (auth.uid() = user_id);

create policy "Users can update their own learning progress"
on public.learning_progress for update
to authenticated
using (auth.uid() = user_id)
with check (auth.uid() = user_id);

create index if not exists learning_progress_user_created_idx
on public.learning_progress (user_id, created_at desc);
