-- ---------- 0. Umumiy yordamchi funksiya ----------
create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

-- ---------- 1. profiles (har bir foydalanuvchiga bitta qator) ----------
create table if not exists public.profiles (
  id           uuid primary key references auth.users(id) on delete cascade,
  display_name text check (display_name is null or char_length(display_name) <= 60),
  grade        smallint check (grade is null or grade between 1 and 12),
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);

alter table public.profiles enable row level security;

drop policy if exists "profiles_select_own" on public.profiles;
create policy "profiles_select_own" on public.profiles
  for select to authenticated using ((select auth.uid()) = id);

drop policy if exists "profiles_insert_own" on public.profiles;
create policy "profiles_insert_own" on public.profiles
  for insert to authenticated with check ((select auth.uid()) = id);

drop policy if exists "profiles_update_own" on public.profiles;
create policy "profiles_update_own" on public.profiles
  for update to authenticated
  using ((select auth.uid()) = id) with check ((select auth.uid()) = id);

drop trigger if exists profiles_set_updated_at on public.profiles;
create trigger profiles_set_updated_at
  before update on public.profiles
  for each row execute function public.set_updated_at();

-- Ro'yxatdan o'tganda profil avtomatik yaratiladi
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, display_name)
  values (
    new.id,
    left(coalesce(nullif(new.raw_user_meta_data ->> 'display_name', ''), split_part(new.email, '@', 1)), 60)
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

revoke all on function public.handle_new_user() from public, anon, authenticated;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- Allaqachon mavjud foydalanuvchilar uchun profil yaratish
insert into public.profiles (id, display_name)
select u.id, left(split_part(u.email, '@', 1), 60)
from auth.users u
on conflict (id) do nothing;

-- ---------- 2. learning_progress (test natijalari va faollik) ----------
create table if not exists public.learning_progress (
  id            bigint generated by default as identity primary key,
  user_id       uuid not null default auth.uid() references auth.users(id) on delete cascade,
  subject       text not null check (char_length(subject) between 1 and 60),
  activity_type text not null check (activity_type in ('quiz', 'lesson', 'goal')),
  score         integer,
  details       jsonb not null default '{}'::jsonb,
  created_at    timestamptz not null default now()
);

-- Eski jadval bo'lsa ham mos holatga keltirish
alter table public.learning_progress alter column user_id set default auth.uid();

do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'learning_progress_score_range') then
    alter table public.learning_progress
      add constraint learning_progress_score_range
      check (score is null or score between 0 and 100) not valid;
  end if;
  if not exists (select 1 from pg_constraint where conname = 'learning_progress_details_size') then
    alter table public.learning_progress
      add constraint learning_progress_details_size
      check (octet_length(details::text) <= 4000) not valid;
  end if;
end $$;

alter table public.learning_progress enable row level security;

